#!/usr/bin/env python3
"""Generates the MDM files for the IDE bridge (docs/MDM.md) into dist/mdm/.

Host names come from .env (ID_HOST, AI_HOST). Nothing secret goes into these files.

  cloud.slatff.ide-bridge.plist                  Jamf: Application & Custom Settings > Upload,
                                                 preference domain cloud.slatff.ide-bridge
  slatff-ide-bridge-settings.mobileconfig        same settings as a profile (any MDM, e.g. Iru Custom Profile)
  jamf-install-ide-bridge.sh                     Jamf policy script: bridge.py + LaunchAgent for all users
  jamf-uninstall-ide-bridge.sh                   removes both
  xcode-coding-assistant-off.mobileconfig        test: CodingAssistantAllowExternalIntegrations = false
  xcode-on-device-models-off.mobileconfig        test: IDEProhibitOnDeviceModelInteraction = true (unverified key)

Usage: python3 scripts/make-mdm-files.py [--ide xcode]
"""
import base64
import os
import plistlib
import sys
import uuid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "dist", "mdm")
NS = uuid.UUID("6f1c3a52-6a0e-4f43-9a51-0d5c0f1b7e01")     # fixed: same UUIDs on every run
LABEL = "cloud.slatff.ide-bridge"
DIR = "/Library/Application Support/SLATFF"


def env():
    vals = {}
    try:
        for line in open(os.path.join(ROOT, ".env")):
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.rstrip("\n").split("=", 1)
                vals[k.strip()] = v.strip()
    except FileNotFoundError:
        sys.exit("no .env: run ./scripts/bootstrap.sh first")
    for k in ("ID_HOST", "AI_HOST"):
        if not vals.get(k):
            sys.exit(f"{k} is empty in .env")
    return vals


def uid(name):
    return str(uuid.uuid5(NS, name)).upper()


def profile(ident, name, description, payloads):
    return {"PayloadType": "Configuration", "PayloadVersion": 1, "PayloadScope": "System",
            "PayloadIdentifier": ident, "PayloadUUID": uid(ident), "PayloadDisplayName": name,
            "PayloadDescription": description, "PayloadOrganization": "SLATFF.Cloud",
            "PayloadContent": payloads}


def payload(ptype, ident, name, content):
    p = {"PayloadType": ptype, "PayloadVersion": 1, "PayloadIdentifier": ident, "PayloadUUID": uid(ident),
         "PayloadDisplayName": name}
    p.update(content)
    return p


def write_plist(name, data):
    with open(os.path.join(OUT, name), "wb") as f:
        plistlib.dump(data, f)
    print("wrote dist/mdm/" + name)


def write_text(name, text, mode=0o644):
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write(text)
    os.chmod(path, mode)
    print("wrote dist/mdm/" + name)


def main():
    ide = sys.argv[sys.argv.index("--ide") + 1] if "--ide" in sys.argv else "xcode"
    e = env()
    os.makedirs(OUT, exist_ok=True)
    settings = {"Issuer": f"https://{e['ID_HOST']}/realms/slatff",
                "Gateway": f"https://{e['AI_HOST']}/gateway/v1", "IDE": ide, "Port": 11435}

    # 1. settings: plain plist for Jamf, and a profile for any MDM
    write_plist(f"{LABEL}.plist", settings)
    write_plist("slatff-ide-bridge-settings.mobileconfig", profile(
        "cloud.slatff.profile.ide-bridge-settings", "SLATFF IDE bridge settings",
        "Keycloak and gateway addresses for the SLATFF IDE bridge. Users cannot change them.",
        [payload("com.apple.ManagedClient.preferences", "cloud.slatff.payload.ide-bridge-settings",
                 "IDE bridge settings",
                 {"PayloadContent": {LABEL: {"Forced": [{"mcx_preference_settings": settings}]}}})]))

    # 2. install and uninstall scripts for a Jamf policy (run as root)
    bridge = open(os.path.join(ROOT, "ide-bridge", "bridge.py"), "rb").read()
    b64 = base64.encodebytes(bridge).decode()
    agent = plistlib.dumps({
        "Label": LABEL,
        "ProgramArguments": ["/bin/sh", "-c",
                             f"exec /usr/bin/python3 '{DIR}/bridge.py' serve >> \"$HOME/Library/Logs/slatff-ide-bridge.log\" 2>&1"],
        "EnvironmentVariables": {"PYTHONUNBUFFERED": "1"},
        "RunAtLoad": True, "KeepAlive": True, "ThrottleInterval": 30,
        "LimitLoadToSessionType": "Aqua", "ProcessType": "Background"}).decode()
    write_text("jamf-install-ide-bridge.sh", f"""#!/bin/bash
# SLATFF IDE bridge for all users of this Mac. Jamf policy script, runs as root.
# Generated by scripts/make-mdm-files.py from ide-bridge/bridge.py. Settings come from the
# configuration profile (domain {LABEL}). Each user still signs in once:
#   /usr/bin/python3 "{DIR}/bridge.py" login
set -e
if ! /usr/bin/xcode-select -p >/dev/null 2>&1; then
  echo "needs Xcode or the Command Line Tools for /usr/bin/python3"; exit 1
fi
mkdir -p "{DIR}"
/usr/bin/base64 -D > "{DIR}/bridge.py" <<'B64'
{b64}B64
chown root:wheel "{DIR}/bridge.py"; chmod 755 "{DIR}/bridge.py"
cat > /Library/LaunchAgents/{LABEL}.plist <<'PLIST'
{agent}PLIST
chown root:wheel /Library/LaunchAgents/{LABEL}.plist; chmod 644 /Library/LaunchAgents/{LABEL}.plist
U=$(/usr/bin/stat -f %Su /dev/console)
if [ -n "$U" ] && [ "$U" != root ] && [ "$U" != _mbsetupuser ]; then
  N=$(/usr/bin/id -u "$U")
  /bin/launchctl bootout "gui/$N/{LABEL}" 2>/dev/null || true
  rm -f "/Users/$U/Library/LaunchAgents/{LABEL}.plist"
  /bin/launchctl bootstrap "gui/$N" /Library/LaunchAgents/{LABEL}.plist
  echo "started for $U"
fi
echo "SLATFF IDE bridge installed: {DIR}/bridge.py, /Library/LaunchAgents/{LABEL}.plist"
""", 0o755)
    write_text("jamf-uninstall-ide-bridge.sh", f"""#!/bin/bash
# Removes the SLATFF IDE bridge installed by jamf-install-ide-bridge.sh. Runs as root.
# Sign-ins and local keys stay in each user's Keychain.
U=$(/usr/bin/stat -f %Su /dev/console)
if [ -n "$U" ] && [ "$U" != root ]; then
  /bin/launchctl bootout "gui/$(/usr/bin/id -u "$U")/{LABEL}" 2>/dev/null || true
fi
rm -f /Library/LaunchAgents/{LABEL}.plist "{DIR}/bridge.py"
rmdir "{DIR}" 2>/dev/null || true
echo "SLATFF IDE bridge removed"
""", 0o755)

    # 3. Xcode control tests (part B step 4)
    write_plist("xcode-coding-assistant-off.mobileconfig", profile(
        "cloud.slatff.profile.xcode-coding-assistant-off", "TEST Xcode coding assistant off",
        "Test profile: CodingAssistantAllowExternalIntegrations = false (Apple: turns the coding assistant off).",
        [payload("com.apple.dt.Xcode", "cloud.slatff.payload.xcode-coding-assistant-off", "Xcode",
                 {"CodingAssistantAllowExternalIntegrations": False})]))
    write_plist("xcode-on-device-models-off.mobileconfig", profile(
        "cloud.slatff.profile.xcode-on-device-models-off", "TEST Xcode on-device models off",
        "Test profile: IDEProhibitOnDeviceModelInteraction = true (key not in Apple's public docs; effect unverified).",
        [payload("com.apple.dt.Xcode", "cloud.slatff.payload.xcode-on-device-models-off", "Xcode",
                 {"IDEProhibitOnDeviceModelInteraction": True})]))


if __name__ == "__main__":
    main()
